#!/usr/bin/env python3
"""Translates the RegExLib Subset benchmarks (regex-smt-benchmarks/regexlib_subset) into
history_syntax regexes over an alphabet of character-class representatives.

Usage: translate.py <path/to/regexlib_subset> > regexlib_subset.rs
"""
import glob, os, re, sys

def tokenize(text):
    return re.findall(r'\(|\)|"[^"]*"|[^\s()"]+', text)

def parse(tokens, i=0):
    if tokens[i] == '(':
        i += 1
        items = []
        while tokens[i] != ')':
            node, i = parse(tokens, i)
            items.append(node)
        return items, i + 1
    return tokens[i], i + 1

def char(literal):
    text = literal[1:-1]
    escaped = re.fullmatch(r'\\u\{([0-9a-fA-F]+)\}', text)
    if escaped:
        return int(escaped[1], 16)
    assert len(text) == 1, literal
    return ord(text)

root = sys.argv[1]
regexes = {}  # smt body -> (index, regexlib pattern, ast)
pairs = []  # (file, left index, right index, included)
for path in sorted(glob.glob(os.path.join(root, '*', 'notsubset_*.smt2'))):
    text = open(path, encoding='utf-8').read()
    sides = []
    for name in ('regexA', 'regexB'):
        body = re.search(r'\(assert \(= %s (.*)\)\)\n' % name, text)[1]
        pattern = re.search(r'; %s = (.*)' % name, text)[1]
        if body not in regexes:
            regexes[body] = (len(regexes), pattern, parse(tokenize(body))[0])
        sides.append(regexes[body][0])
    included = os.path.basename(os.path.dirname(path)) == 'unsat'
    pairs.append((os.path.relpath(path, root), sides[0], sides[1], included))

ranges = set()
def collect(node):
    if isinstance(node, list):
        if node and node[0] == 're.range':
            ranges.add((char(node[1]), char(node[2])))
        for child in node:
            collect(child)
for _, _, ast in regexes.values():
    collect(ast)
cuts = sorted({0, 256} | {lo for lo, _ in ranges} | {hi + 1 for _, hi in ranges})
classes = [(cuts[k], cuts[k + 1] - 1) for k in range(len(cuts) - 1)]

def representatives(lo, hi):
    inside = [(a, b) for a, b in classes if lo <= a and b <= hi]
    assert sum(b - a + 1 for a, b in inside) == hi - lo + 1, (lo, hi)
    return [a for a, _ in inside]

class_names = {}  # tuple of representatives -> (const name, origin)
def class_const(reps, origin):
    reps = tuple(reps)
    if reps not in class_names:
        class_names[reps] = ('CLASS_%d' % len(class_names), origin)
    return class_names[reps][0]

def flatten(node, op):
    if isinstance(node, list) and node and node[0] == op:
        return [item for child in node[1:] for item in flatten(child, op)]
    return [node]

def is_range(node):
    return isinstance(node, list) and node and node[0] == 're.range'

def printable(code):
    return chr(code) if 0x21 <= code <= 0x7e else '\\x%02x' % code

def describe(node):
    lo, hi = char(node[1]), char(node[2])
    return printable(lo) if lo == hi else '%s-%s' % (printable(lo), printable(hi))

def emit(node):
    if isinstance(node, str):
        raise ValueError(node)
    head = node[0]
    if head == 'str.to_re':
        assert node[1] == '""', node
        return 'RegexExpr::epsilon()'
    if head == 're.range':
        lo, hi = char(node[1]), char(node[2])
        return 'class(%s)' % class_const(representatives(lo, hi), describe(node))
    if head == 're.union':
        children = flatten(node, 're.union')
        reps = sorted({r for c in children if is_range(c) for r in representatives(char(c[1]), char(c[2]))})
        origin = ''.join(describe(c) for c in children if is_range(c))
        parts = (['class(%s)' % class_const(reps, origin)] if reps else []) + [emit(c) for c in children if not is_range(c)]
        return parts[0] if len(parts) == 1 else 'RegexExpr::union([%s])' % ', '.join(parts)
    if head == 're.++':
        parts = [emit(c) for c in flatten(node, 're.++') if not (isinstance(c, list) and c[0] == 'str.to_re')]
        return parts[0] if len(parts) == 1 else 'RegexExpr::concat([%s])' % ', '.join(parts)
    if head == 're.*':
        return 'RegexExpr::star(%s)' % emit(node[1])
    if head == 're.+':
        return 'plus(%s)' % emit(node[1])
    if head == 're.opt':
        return 'opt(%s)' % emit(node[1])
    if isinstance(head, list) and head[:2] == ['_', 're.loop']:
        return 'repeat(%s, %s, %s)' % (emit(node[1]), head[2], head[3])
    raise ValueError(head)

bodies = [(index, pattern, emit(ast)) for index, pattern, ast in sorted(regexes.values())]

out = sys.stdout
out.write('//! RegExLib Subset benchmarks translated to `history_syntax` regexes. Generated by\n')
out.write('//! `translate.py`; do not edit by hand.\n\n')
out.write('use history_syntax::{AtomPattern, Comparison, Component, Component3, ComponentPattern, Event, N3, RegexExpr, TestExpr};\n\n')
out.write('/// One character of the 8-bit alphabet, carried as the action.\n')
out.write('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub struct Char(pub u8);\n\n')
out.write('''impl Event for Char {
    type Component = Component3<(), u8, ()>;
    type Arity = N3;

    fn component(self, index: usize) -> Self::Component {
        match index {
            0 => Component3::C0(()),
            1 => Component3::C1(self.0),
            _ => Component3::C2(()),
        }
    }

    fn coordinate(component: Self::Component) -> usize {
        match component {
            Component3::C0(_) => 0,
            Component3::C1(_) => 1,
            Component3::C2(_) => 2,
        }
    }
}

''')
out.write('/// One representative per class of characters that no range of the dataset tells apart.\n')
out.write('pub const ALPHABET: [u8; %d] = [%s];\n\n' % (len(classes), ', '.join('0x%02x' % a for a, _ in classes)))
out.write('/// One inclusion instance: `left ⊑ right` is `included` in the original benchmark.\n')
out.write('pub struct Instance {\n    pub file: &\'static str,\n    pub left: fn() -> RegexExpr<Char>,\n    pub right: fn() -> RegexExpr<Char>,\n    pub included: bool,\n}\n\n')
out.write('pub const INSTANCES: [Instance; %d] = [\n' % len(pairs))
for file, left, right, included in pairs:
    out.write('    Instance { file: "%s", left: regex_%d, right: regex_%d, included: %s },\n' % (file, left, right, 'true' if included else 'false'))
out.write('];\n\n')
for reps, (name, origin) in sorted(class_names.items(), key=lambda item: int(item[1][0].split('_')[1])):
    out.write('/// `[%s]`\n' % origin)
    out.write('const %s: &[u8] = &[%s];\n' % (name, ', '.join('0x%02x' % r for r in reps)))
out.write('\n')
out.write('''/// One event whose character is one of `reps`.
fn class(reps: &[u8]) -> RegexExpr<Char> {
    RegexExpr::test(TestExpr::or(reps.iter().map(|&rep| {
        TestExpr::atom(Comparison::Eq, AtomPattern::new(Component(1), ComponentPattern::constant(Component3::C1(rep))))
    })))
}

/// `re.opt`: zero or one.
fn opt(regex: RegexExpr<Char>) -> RegexExpr<Char> {
    RegexExpr::union([RegexExpr::epsilon(), regex])
}

/// `re.+`: one or more.
fn plus(regex: RegexExpr<Char>) -> RegexExpr<Char> {
    RegexExpr::concat([regex.clone(), RegexExpr::star(regex)])
}

/// `(_ re.loop lo hi)`: `lo` copies followed by `hi - lo` nested optional copies.
fn repeat(regex: RegexExpr<Char>, lo: usize, hi: usize) -> RegexExpr<Char> {
    let mut tail = RegexExpr::epsilon();
    for _ in lo..hi {
        tail = opt(RegexExpr::concat([regex.clone(), tail]));
    }
    RegexExpr::concat((0..lo).map(|_| regex.clone()).chain((lo < hi).then_some(tail)))
}

''')
for index, pattern, body in bodies:
    out.write('/// `%s`\n' % pattern)
    out.write('fn regex_%d() -> RegexExpr<Char> {\n    %s\n}\n\n' % (index, body))
